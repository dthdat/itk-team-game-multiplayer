import { test } from 'node:test';
import assert from 'node:assert/strict';
import { Store } from '../dist/server/store.js';
import { Accounts, verifyPassword } from '../dist/server/accounts.js';
import { randomUUID } from 'node:crypto';

test('invite accounts use Argon2id, opaque sessions, persistent profiles and verified-only leaderboards', async () => {
  const store=new Store(':memory:'); const accounts=new Accounts(store.db);
  const invite=accounts.issueInvite(1);
  const registered=await accounts.register({invitation:invite,loginId:'Engineer.One',password:'Correct horse battery staple 42'});
  assert.match(registered.session.token,/^[A-Za-z0-9_-]{40,}$/);
  const savedHash=store.db.prepare('SELECT password_hash FROM users WHERE id=?').get(registered.id).password_hash;
  assert.equal(savedHash.includes('Correct horse'),false);
  assert.equal(await verifyPassword('Correct horse battery staple 42',savedHash),true);
  assert.equal(accounts.session(registered.session.token).id,registered.id);
  assert.equal(accounts.session('forged'),undefined);
  await assert.rejects(accounts.login({loginId:'no.such.user',password:'Wrong password 123'}),/Invalid login or password/);
  await assert.rejects(accounts.register({invitation:invite,loginId:'second.user',password:'Correct horse battery staple 42'}),/unavailable/i);
  accounts.setProfile(registered.id,'Engineer One','powertrain',{style:'helmet'});
  assert.equal(store.guestById(registered.id).avatar.style,'helmet');
  assert.throws(()=>accounts.setProfile(registered.id,'Engineer One','battery',{}),/cannot be changed/i);
  assert.equal(store.guestById(registered.id).expires>1e12,true);
  const submission={submissionId:randomUUID(),missionId:'onboard',answer:'This is a draft answer'};
  assert.equal(accounts.submit(registered.id,submission).state,'pending');
  assert.equal(accounts.submit(registered.id,submission).duplicate,true);
  assert.throws(()=>accounts.submit(registered.id,{...submission,answer:'changed'}),/different content/);
  assert.equal(accounts.leaderboard()[0].xp,0);
  const demo=store.createGuest().guest;store.profile(demo,'Guest Engineer','battery');
  assert.equal(accounts.submit(demo.id,{submissionId:randomUUID(),missionId:'release',answer:'A guest may submit any of the eight briefs while grading is disabled.'}).state,'pending');
  assert.equal(store.progress(demo.id).xp,0);
  store.savePosition(registered.id,2.5,3.25,Math.PI/2,Date.now());
  assert.deepEqual(store.position(registered.id).x,2.5);
  assert.equal(accounts.account(registered.id).lastLoginAt>0,true);
  const exported=await accounts.export(registered.id); assert.equal(exported.submissions[0].answer,submission.answer);
  assert.equal(await accounts.verifyCurrentPassword(registered.id,'Correct horse battery staple 42'),true);
  const tempPassword=await accounts.adminRecover('Engineer.One');
  assert.equal(accounts.session(registered.session.token),undefined);
  const recovered=await accounts.login({loginId:'engineer.one',password:tempPassword});
  assert.equal(accounts.session(recovered.session.token).id,registered.id);
  assert.equal(accounts.session(recovered.session.token).mustChangePassword,true);
  await accounts.changePassword(registered.id,{currentPassword:tempPassword,newPassword:'A fresh permanent password 99'});
  assert.equal(accounts.session(recovered.session.token),undefined);
  const afterRecovery=await accounts.login({loginId:'engineer.one',password:'A fresh permanent password 99'});
  assert.equal(accounts.session(afterRecovery.session.token).mustChangePassword,false);
  store.prune();assert.ok(accounts.session(afterRecovery.session.token));
  await accounts.adminRecover('engineer.one');
  await accounts.adminRecover('engineer.one');
  await assert.rejects(accounts.adminRecover('engineer.one'),/temporarily unavailable/i);
  accounts.deleteAccount(registered.id);store.deleteGuest(registered.id);
  assert.equal(accounts.session(registered.session.token),undefined);
  assert.equal(await accounts.export(registered.id),undefined);
  store.close();
});
